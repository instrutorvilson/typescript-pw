function somar(n1: number, n2:number):number{
    return n1 + n2
}

function subtrair(n1: number, n2:number):number{
    return n1 - n2
}

function multiplicar(n1: number, n2:number):number{
    return n1 * n2
}

function dividir(n1: number, n2:number):number{
    if(n2 != 0)
      return n1 / n2
    else
      return 0
}